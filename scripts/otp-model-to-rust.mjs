// Turns otp-detect's src/model-data.ts into the Rust pe-otp includes (core/crates/pe-otp/model/model.rs).
// Run by scripts/update-otp-model.sh.
//
//   node scripts/otp-model-to-rust.mjs <otp-detect>/src/model-data.ts <out.rs>

import fs from 'node:fs';

const [data, out] = process.argv.slice(2);
if (!data || !out) {
    console.error('usage: node scripts/otp-model-to-rust.mjs <model-data.ts> <out.rs>');
    process.exit(1);
}
const source = fs.readFileSync(data, 'utf8');
const start = source.indexOf('{', source.indexOf('export const MODEL'));
const end = source.lastIndexOf('}');
const model = JSON.parse(source.slice(start, end + 1));

// Rust float literals that read back as the same f64: JavaScript prints the shortest representation
// that round-trips, and Rust parses a literal correctly rounded
const float = x => {
    if (!Number.isFinite(x)) {
        throw new Error(`not a finite number: ${x}`);
    }
    if (Object.is(x, -0)) {
        return '-0.0';
    }
    const s = String(x);
    return /[.e]/.test(s) ? s : s + '.0';
};
const int = x => {
    if (!Number.isInteger(x)) {
        throw new Error(`not an integer: ${x}`);
    }
    return String(x);
};
const list = (values, format) => `&[${values.map(format).join(', ')}]`;

const lines = [
    '// Generated by scripts/update-otp-model.sh from otp-detect src/model-data.ts. Do not edit.',
    'Model {',
    `    version: ${JSON.stringify(String(model.version))},`,
    `    feature_names: ${list(model.featureNames, n => JSON.stringify(n))},`,
    `    threshold: ${float(model.threshold)},`,
    '    trees: &['
];
for (const tree of model.trees) {
    const n = tree.feature.length;
    if ([tree.threshold, tree.left, tree.right].some(a => a.length !== n)) {
        throw new Error('tree arrays of different lengths');
    }
    lines.push(
        '        Tree {',
        `            feature: ${list(tree.feature, int)},`,
        `            threshold: ${list(tree.threshold, float)},`,
        `            left: ${list(tree.left, int)},`,
        `            right: ${list(tree.right, int)},`,
        `            leaves: ${list(tree.leaves, float)},`,
        '        },'
    );
}
lines.push('    ],', '}', '');
fs.writeFileSync(out, lines.join('\n'));
console.log(`${model.trees.length} trees, ${model.featureNames.length} features, threshold ${model.threshold}`);
