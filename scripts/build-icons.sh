#!/usr/bin/env bash
# Turns the toolbar icons (Fluent UI System Icons, SVG, in app/res/icons) into the bitmap strips the classic
# toolbars take, and writes app/src/icons.h with their order and sizes and app/res/toolbar.rc with the strips as
# resources. Run after changing an icon or the lists below; the
# strips and the header are committed, so the Windows build needs neither the SVGs' tools nor this script.
#
# The classic common controls (no ComCtl6) draw image lists without alpha. Each icon is therefore drawn over the
# button face color, which is then the transparent color of the strip: the smoothed edges blend into the toolbar.
#
#   scripts/build-icons.sh        (needs rsvg-convert and ImageMagick: brew install librsvg imagemagick)
set -euo pipefail
cd "$(dirname "$0")/.."

SVG=app/res/icons
OUT=app/res/toolbar
FACE='#F0F0F0'
# the background of the folder tree and the message list, the transparent color of their strips
WINDOW='#FFFFFF'
# the icons' own color, Fluent's neutral foreground
INK='#242424'

# the big buttons of the main window and the compose window, in strip order
TOOLBAR=(mail_add arrow_reply arrow_reply_all arrow_forward print delete arrow_sync mail_read mail_unread send save attach mail_prohibited mail_checkmark archive arrow_up arrow_down)
# the folder tree: the account, then a folder of each kind
FOLDERS=(mailbox folder mail_inbox send drafts delete mail_prohibited archive flag mail_multiple)
# the message list: attachment, flag
LIST=(attach flag search dismiss calendar_ltr)
# the small ones of the format bar
FORMAT=(text_bold text_italic text_underline text_color text_number_list_ltr text_bullet_list_ltr text_indent_decrease_ltr
    text_indent_increase_ltr text_align_left text_align_center text_align_right link line_horizontal_1 image)

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
mkdir -p "$OUT"

# source ICON SIZE: the SVG drawn for that size: Fluent's own 16 or 20 pixel design where there is one (crisper
# than the 24 pixel one scaled down), else the closest there is
source() {
    local icon=$1 size=$2 order
    if [ "$size" -le 16 ]; then order=(_16 _20 ""); elif [ "$size" -le 20 ]; then order=(_20 "" _16); else order=("" _20 _16); fi
    for suffix in "${order[@]}"; do
        if [ -f "$SVG/$icon$suffix.svg" ]; then echo "$SVG/$icon$suffix.svg"; return; fi
    done
    echo "no SVG for $icon" >&2
    exit 1
}

# strip NAME SIZE BACKGROUND ICON...: the icons side by side at SIZE pixels over BACKGROUND, a 24-bit BMP
strip() {
    local name=$1 size=$2 background=$3
    shift 3
    local frames=()
    for icon in "$@"; do
        sed "s/#212121/$INK/g" "$(source "$icon" "$size")" > "$work/$icon.svg"
        rsvg-convert -w "$size" -h "$size" -b "$background" "$work/$icon.svg" -o "$work/$icon-$size.png"
        frames+=("$work/$icon-$size.png")
    done
    magick "${frames[@]}" +append -background "$background" -alpha remove -type TrueColor "BMP3:$OUT/$name-$size.bmp"
}

# kind NAME FIRST_ID BACKGROUND ARRAY ENUM PREFIX SIZE... -- ICON...: the strips of one kind, one per size (100%,
# 125%, 150% and 200%), with their lines of the resource script, their table and the enum of their icons
kind() {
    local name=$1 id=$2 background=$3 array=$4 enum=$5 prefix=$6
    shift 6
    local sizes=() rows=()
    while [ "$1" != -- ]; do sizes+=("$1"); shift; done
    shift
    for size in "${sizes[@]}"; do
        strip "$name" "$size" "$background" "$@"
        echo "$id BITMAP \"toolbar/$name-$size.bmp\"" >> "$work/rc"
        rows+=("{$id, $size, 0x${background#\#}}")
        id=$((id + 1))
    done
    (IFS=,; echo "constexpr IconStrip $array[] = {${rows[*]}};" | sed 's/},{/}, {/g') >> "$work/tables"
    {
        echo
        echo "enum $enum : int {"
        local i=0
        for icon in "$@"; do echo "    ${prefix}_$(echo "$icon" | tr a-z A-Z) = $i,"; i=$((i + 1)); done
        echo '};'
    } >> "$work/enums"
}

: > "$work/rc"
: > "$work/tables"
: > "$work/enums"
SMALL_SIZES=(16 20 24 32)
kind toolbar 10 "$FACE" kToolbarStrips ToolbarIcon ICON 24 30 36 48 -- "${TOOLBAR[@]}"
kind format 20 "$FACE" kFormatStrips FormatIcon FORMAT "${SMALL_SIZES[@]}" -- "${FORMAT[@]}"
kind folders 30 "$WINDOW" kFolderStrips FolderIcon FOLDER "${SMALL_SIZES[@]}" -- "${FOLDERS[@]}"
kind list 40 "$WINDOW" kListStrips ListIcon LIST "${SMALL_SIZES[@]}" -- "${LIST[@]}"

{
    echo '// Generated by scripts/build-icons.sh: the toolbar strips (icons/*.svg), one per size, 100% to 200%'
    cat "$work/rc"
} > app/res/toolbar.rc

{
    echo '// Generated by scripts/build-icons.sh: the strips of app/res/toolbar by size (app/res/toolbar.rc), smallest'
    echo '// first, and the positions of the icons in them.'
    echo '#pragma once'
    echo
    echo 'struct IconStrip {'
    echo '    int resource;'
    echo '    int size;'
    echo '    // what the icons were drawn over, 0xRRGGBB: the transparent color of the strip'
    echo '    unsigned background;'
    echo '};'
    cat "$work/tables"
    cat "$work/enums"
} > app/src/icons.h
# the app's own icon (app/res/app-icon.svg, the mark of inboxclassic.com): every size Windows asks for, with alpha
icon_frames=()
for size in 16 20 24 32 40 48 64 256; do
    rsvg-convert -w "$size" -h "$size" app/res/app-icon.svg -o "$work/app-$size.png"
    icon_frames+=("$work/app-$size.png")
done
magick "${icon_frames[@]}" app/res/app.ico

# the sign-in buttons of Add Mail Account (app/res/brands), the providers' own artwork, unchanged: Google's PNG with
# its transparent margin trimmed, Microsoft's SVG at three times its size; the app scales them with WIC
magick app/res/brands/google-sign-in-source.png -trim +repage app/res/brands/google-sign-in.png
rsvg-convert -z 3 app/res/brands/microsoft-sign-in.svg -o app/res/brands/microsoft-sign-in.png

echo "toolbar strips in $OUT and app/res/toolbar.rc, order and sizes in app/src/icons.h, the app icon in app/res/app.ico"
