#!/usr/bin/env bash
# Turns the toolbar icons (Fluent UI System Icons, SVG, in app/res/icons) into the bitmap strips the classic
# toolbars take, and writes app/src/icons.h with their order and sizes and app/res/toolbar.rc with the strips as
# resources. Run after changing an icon or the lists below; the
# strips and the header are committed, so the Windows build needs neither the SVGs' tools nor this script.
#
# The classic common controls (no ComCtl6) draw image lists without alpha. Each icon is therefore drawn over the
# button face color, which is then the transparent color of the strip: the smoothed edges blend into the toolbar.
#
#   scripts/build-icons.sh        (needs rsvg-convert and ImageMagick: brew install librsvg imagemagick)
set -euo pipefail
cd "$(dirname "$0")/.."

SVG=app/res/icons
OUT=app/res/toolbar
FACE='#F0F0F0'
# the icons' own color, Fluent's neutral foreground
INK='#242424'

# the big buttons of the main window and the compose window, in strip order
TOOLBAR=(mail_add arrow_reply arrow_reply_all arrow_forward print delete arrow_sync mail_read mail_unread send send_clock save attach)
# the small ones of the format bar
FORMAT=(text_bold text_italic text_underline text_color text_number_list_ltr text_bullet_list_ltr text_indent_decrease_ltr
    text_indent_increase_ltr text_align_left text_align_center text_align_right link line_horizontal_1 image)

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
mkdir -p "$OUT"

# strip NAME SIZE ICON...: the icons side by side at SIZE pixels, a 24-bit BMP
strip() {
    local name=$1 size=$2
    shift 2
    local frames=()
    for icon in "$@"; do
        sed "s/#212121/$INK/g" "$SVG/$icon.svg" > "$work/$icon.svg"
        rsvg-convert -w "$size" -h "$size" -b "$FACE" "$work/$icon.svg" -o "$work/$icon-$size.png"
        frames+=("$work/$icon-$size.png")
    done
    magick "${frames[@]}" +append -background "$FACE" -alpha remove -type TrueColor "BMP3:$OUT/$name-$size.bmp"
}

# 100%, 125%, 150% and 200% of 24 and 16 pixels, and the first resource ID of each kind
TOOLBAR_SIZES=(24 30 36 48)
FORMAT_SIZES=(16 20 24 32)
TOOLBAR_ID=10
FORMAT_ID=20
for size in "${TOOLBAR_SIZES[@]}"; do strip toolbar "$size" "${TOOLBAR[@]}"; done
for size in "${FORMAT_SIZES[@]}"; do strip format "$size" "${FORMAT[@]}"; done

# strips KIND FIRST_ID SIZE...: lines of the resource script, and the table for the C++ side
rc_lines() {
    local kind=$1 id=$2
    shift 2
    for size in "$@"; do echo "$id BITMAP \"toolbar/$kind-$size.bmp\""; id=$((id + 1)); done
}
table() {
    local id=$1
    shift
    local rows=()
    for size in "$@"; do rows+=("{$id, $size}"); id=$((id + 1)); done
    (IFS=,; echo "${rows[*]}" | sed 's/},{/}, {/g')
}
{
    echo '// Generated by scripts/build-icons.sh: the toolbar strips (icons/*.svg), one per size, 100% to 200%'
    rc_lines toolbar "$TOOLBAR_ID" "${TOOLBAR_SIZES[@]}"
    rc_lines format "$FORMAT_ID" "${FORMAT_SIZES[@]}"
} > app/res/toolbar.rc

{
    echo '// Generated by scripts/build-icons.sh: the positions of the icons in the toolbar strips (app/res/toolbar), and'
    echo '// the strips by size (app/res/toolbar.rc), smallest first.'
    echo '#pragma once'
    echo
    echo 'struct IconStrip {'
    echo '    int resource;'
    echo '    int size;'
    echo '};'
    echo "constexpr IconStrip kToolbarStrips[] = {$(table "$TOOLBAR_ID" "${TOOLBAR_SIZES[@]}")};"
    echo "constexpr IconStrip kFormatStrips[] = {$(table "$FORMAT_ID" "${FORMAT_SIZES[@]}")};"
    echo
    echo 'enum ToolbarIcon : int {'
    for i in "${!TOOLBAR[@]}"; do echo "    ICON_$(echo "${TOOLBAR[$i]}" | tr a-z A-Z) = $i,"; done
    echo '};'
    echo
    echo 'enum FormatIcon : int {'
    for i in "${!FORMAT[@]}"; do echo "    FORMAT_$(echo "${FORMAT[$i]}" | tr a-z A-Z) = $i,"; done
    echo '};'
} > app/src/icons.h
echo "toolbar strips in $OUT and app/res/toolbar.rc, order and sizes in app/src/icons.h"
