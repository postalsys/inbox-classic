// Writes src/parser/entities.rs, the named character references of HTML from postal-mime's table
// (src/html-entities.ts), for the HTML to text conversion. Run with postal-mime next to this
// repository:
//
//     node --experimental-strip-types generate-entities.mjs [path to postal-mime]

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const postalMime = resolve(process.argv[2] || resolve(here, '../../../../../postal-mime'));
const { htmlEntities } = await import(pathToFileURL(resolve(postalMime, 'src/html-entities.ts')).href);

// Rust string literal, every non-ASCII character escaped so the source stays plain
const literal = value =>
    '"' +
    [...value]
        .map(c => {
            const code = c.codePointAt(0);
            if (c === '"' || c === '\\') {
                return '\\' + c;
            }
            return code < 0x20 || code > 0x7e ? `\\u{${code.toString(16)}}` : c;
        })
        .join('') +
    '"';

const names = Object.keys(htmlEntities).sort();
let out = "// Generated by tools/generate-entities.mjs from postal-mime's src/html-entities.ts, do not edit.\n\n";
out += '/// Named character references with their text, sorted by name for binary search\n';
out += 'pub(crate) const ENTITIES: &[(&str, &str)] = &[\n';
for (const name of names) {
    out += `    (${literal(name)}, ${literal(htmlEntities[name])}),\n`;
}
out += '];\n';
writeFileSync(resolve(here, '../src/parser/entities.rs'), out);
console.log(`${names.length} entities`);
