// Writes src/special_use_names.rs, the localized folder names that mark special-use folders on
// servers without SPECIAL-USE, from imapflow's tables (src/special-use.ts), so both clients
// recognize the same folders. Run with imapflow built next to this repository:
//
//     node generate-special-use.mjs [path to imapflow]

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const imapflow = resolve(process.argv[2] || resolve(here, '../../../../../imapflow'));
const { names } = await import(pathToFileURL(resolve(imapflow, 'dist/esm/special-use.js')).href);

// GENERIC_TOKENS is not exported, it is read from the source
const source = readFileSync(resolve(imapflow, 'src/special-use.ts'), 'utf8');
const block = source.slice(source.indexOf('const GENERIC_TOKENS'), source.indexOf('].map(token =>'));
const generic = [...block.matchAll(/'([^']+)'/g)].map(m => m[1].toLowerCase().normalize('NFKC'));

// A Rust string literal. Invisible characters (Khmer names separate words with U+200B) are
// written as escapes, so the source shows them
const str = value =>
    '"' +
    [...value]
        .map(c => {
            if (c === '"' || c === '\\') {
                return '\\' + c;
            }
            return /[\u0000-\u001f\u007f\u00ad\u200b-\u200f\u2028-\u202e\u2060-\u206f\ufeff]/.test(c) ? `\\u{${c.codePointAt(0).toString(16)}}` : c;
        })
        .join('') +
    '"';
let out = "// Generated by tools/generate-special-use.mjs from imapflow's src/special-use.ts, do not edit.\n\n";
out += '/// Generic mail nouns that decorate a special-use name without changing it ("Sent Mail")\n';
out += `pub(crate) const GENERIC_TOKENS: &[&str] = &[${generic.map(str).join(', ')}];\n\n`;
out += '/// Known names of special-use folders, folded (lowercase, NFKC), by flag\n';
out += 'pub(crate) const NAMES: &[(&str, &[&str])] = &[\n';
for (const flag of Object.keys(names)) {
    out += `    (${str(flag)}, &[${names[flag].map(str).join(', ')}]),\n`;
}
out += '];\n';
writeFileSync(resolve(here, '../src/special_use_names.rs'), out);
console.log(`${Object.values(names).flat().length} names, ${generic.length} generic tokens`);
